import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '..')
const distDir = path.join(rootDir, 'dist')
const outputHpp = path.join(__dirname, 'dist_embedded.hpp')
const outputCpp = path.join(__dirname, 'dist_embedded.cpp')

const MIME_MAP = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.mjs': 'application/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
  '.woff': 'font/woff',
  '.ttf': 'font/ttf',
  '.txt': 'text/plain; charset=utf-8',
}

function getMime(filePath) {
  const ext = path.extname(filePath).toLowerCase()
  return MIME_MAP[ext] || 'application/octet-stream'
}

function getAllFiles(dir, base = '') {
  let results = []
  if (!fs.existsSync(dir)) return results
  const list = fs.readdirSync(dir)
  for (const file of list) {
    const fullPath = path.join(dir, file)
    const relPath = path.join(base, file)
    const stat = fs.statSync(fullPath)
    if (stat && stat.isDirectory()) {
      results = results.concat(getAllFiles(fullPath, relPath))
    } else {
      results.push({ fullPath, relPath: '/' + relPath.replace(/\\/g, '/') })
    }
  }
  return results
}

function generate() {
  if (!fs.existsSync(distDir)) {
    console.error('Directory dist/ does not exist. Please run npm run build-only first.')
    process.exit(1)
  }

  const files = getAllFiles(distDir)
  console.log(`Found ${files.length} files in dist/`)

  let hpp = `// Auto-generated by generate-assets.js. Do not edit.
#pragma once
#include <cstddef>

struct EmbeddedAsset {
    const char* path;
    const unsigned char* data;
    size_t size;
    const char* mime;
};

extern const EmbeddedAsset EMBEDDED_ASSETS[];
extern const size_t EMBEDDED_ASSETS_COUNT;
`

  let cpp = `// Auto-generated by generate-assets.js. Do not edit.
#include "dist_embedded.hpp"

`

  files.forEach((file, idx) => {
    const buf = fs.readFileSync(file.fullPath)
    const varName = `asset_data_${idx}`
    cpp += `// ${file.relPath} (${buf.length} bytes)\n`
    cpp += `static const unsigned char ${varName}[] = {\n`

    const hexValues = []
    for (let i = 0; i < buf.length; i++) {
      hexValues.push('0x' + buf[i].toString(16).padStart(2, '0'))
      if (hexValues.length >= 16) {
        cpp += '  ' + hexValues.join(', ') + ',\n'
        hexValues.length = 0
      }
    }
    if (hexValues.length > 0) {
      cpp += '  ' + hexValues.join(', ') + ',\n'
    }
    cpp += `};\n\n`
  })

  cpp += `const EmbeddedAsset EMBEDDED_ASSETS[] = {\n`
  files.forEach((file, idx) => {
    const buf = fs.readFileSync(file.fullPath)
    const mime = getMime(file.fullPath)
    cpp += `  { "${file.relPath}", asset_data_${idx}, ${buf.length}, "${mime}" },\n`
  })
  cpp += `};\n\n`
  cpp += `const size_t EMBEDDED_ASSETS_COUNT = ${files.length};\n`

  fs.writeFileSync(outputHpp, hpp, 'utf-8')
  fs.writeFileSync(outputCpp, cpp, 'utf-8')
  console.log(`Generated ${outputHpp} and ${outputCpp}`)
}

generate()
